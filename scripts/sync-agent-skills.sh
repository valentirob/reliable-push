#!/usr/bin/env bash
# Keeps the AI agent context the same for every tool (AGENTS.md "AI agent context").
#
#   scripts/sync-agent-skills.sh          write .claude/skills/<name>/SKILL.md for every .agents/skills/<name>/SKILL.md
#   scripts/sync-agent-skills.sh --check  verify instead (CI): wrappers in sync, rule frontmatter valid, imports exist
#
# .agents/skills is the single source (Antigravity reads it natively). Claude Code reads .claude/skills, so each skill
# gets a thin wrapper there with the same name and description. Real files, not a symlink: a symlink checked out on
# Windows without core.symlinks becomes a one-line text file and Claude Code would see no skills.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
CHECK=false
[ "${1:-}" = "--check" ] && CHECK=true
errors=0
fail() { echo "agent-context: $*" >&2; errors=$((errors + 1)); }

frontmatter_value() { # file key -> value of "key:" inside the leading --- block
  awk -v key="$2" '{sub(/\r$/, "")} NR==1 && $0!="---" {exit} NR>1 && $0=="---" {exit} NR>1 && index($0, key": ")==1 {print substr($0, length(key)+3); exit}' "$1"
}

wrapper() { # name description
  cat <<EOF
---
name: $1
description: $2
---

<!-- Generated by scripts/sync-agent-skills.sh from .agents/skills/$1/SKILL.md. Edit that file, then re-run the script. -->

Read \`.agents/skills/$1/SKILL.md\` and follow it exactly. It is the single source of this skill, shared with
Antigravity and the other tools that read \`AGENTS.md\`.
EOF
}

if [ -L .claude/skills ]; then
  if $CHECK; then fail ".claude/skills is a symlink; run scripts/sync-agent-skills.sh"; else rm .claude/skills; fi
fi

sources=()
for src in .agents/skills/*/SKILL.md; do
  name="$(basename "$(dirname "$src")")"
  sources+=("$name")
  declared="$(frontmatter_value "$src" name)"
  description="$(frontmatter_value "$src" description)"
  [ "$declared" = "$name" ] || fail "$src: name '$declared' differs from its folder '$name'"
  [ -n "$description" ] || fail "$src: missing description"
  target=".claude/skills/$name/SKILL.md"
  expected="$(wrapper "$name" "$description")"
  if $CHECK; then
    [ -f "$target" ] && [ "$(tr -d '\r' < "$target")" = "$expected" ] || fail "$target missing or out of date; run scripts/sync-agent-skills.sh"
  else
    mkdir -p "$(dirname "$target")"
    printf '%s\n' "$expected" > "$target"
  fi
done

# wrappers whose source is gone
if [ -d .claude/skills ]; then
  for dir in .claude/skills/*/; do
    [ -d "$dir" ] || continue
    name="$(basename "$dir")"
    case " ${sources[*]} " in *" $name "*) ;; *)
      if $CHECK; then fail ".claude/skills/$name has no source in .agents/skills"; else rm -rf "$dir"; fi ;;
    esac
  done
fi

# Antigravity silently drops a rule without a valid trigger
for rule in .agents/rules/*.md; do
  trigger="$(frontmatter_value "$rule" trigger)"
  case "$trigger" in
    always_on|manual) ;;
    model_decision) [ -n "$(frontmatter_value "$rule" description)" ] || fail "$rule: model_decision needs a description" ;;
    glob) [ -n "$(frontmatter_value "$rule" globs)" ] || fail "$rule: glob needs globs" ;;
    *) fail "$rule: invalid trigger '$trigger' (always_on, model_decision, glob or manual)" ;;
  esac
  grep -q "\`$rule\`" AGENTS.md || fail "$rule is not listed in the AGENTS.md rules index"
done

# every always_on rule is imported by CLAUDE.md, and every import exists
for rule in .agents/rules/*.md; do
  [ "$(frontmatter_value "$rule" trigger)" = "always_on" ] || continue
  tr -d '\r' < CLAUDE.md | grep -qx "@$rule" || fail "CLAUDE.md does not import the always_on rule $rule (add the line @$rule)"
done
while IFS= read -r line; do
  line="${line%$'\r'}"
  [ -f "${line#@}" ] || fail "CLAUDE.md imports ${line#@}, which does not exist"
done < <(tr -d '\r' < CLAUDE.md | grep -E '^@')

for name in "${sources[@]}"; do
  grep -q "\`$name\`" AGENTS.md || fail "skill $name is not listed in the AGENTS.md skills index"
done

if [ "$errors" -gt 0 ]; then
  echo "agent-context: $errors problem(s)" >&2
  exit 1
fi
if $CHECK; then echo "agent-context: in sync (${#sources[@]} skills)"; else echo "agent-context: wrote ${#sources[@]} Claude Code skill wrappers"; fi
