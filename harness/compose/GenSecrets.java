import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.attribute.PosixFilePermissions;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.MessageDigest;
import java.security.SecureRandom;
import java.security.spec.ECGenParameterSpec;
import java.util.Base64;
import java.util.HexFormat;
import java.util.List;

/**
 * Generates the per-run secrets of the local E2E stack (single-file program, JDK only; runs in the one-shot
 * {@code secrets} compose service): {@code java GenSecrets.java <outDir> [template]}.
 *
 * <p>Writes {@code <outDir>/secrets.env} (env_file of the backend and harness containers) = the non-secret
 * {@code backend.env.template} (default: {@code ./backend.env.template}) followed by, per app ({@code shop},
 * {@code news}, {@code limited}): a random 32-byte sender API key (base64url) for the harness and its SHA-256 hex for
 * the backend, a 32-byte grant secret and a 32-byte webhook HMAC secret (base64url, 43 characters ≥ 32 bytes), plus one
 * P-256 device-token signing key pair (PKCS#8 / SPKI PEM) and the database password. Also writes {@code db.env}
 * (only {@code POSTGRES_PASSWORD}) for the database container. Re-running overwrites both files (mode 600).
 *
 * <p>PEMs are written single-quoted on one line with literal {@code \n} separators: env_file values cannot contain raw
 * newlines, single quotes stop compose from interpolating or unescaping them, and the backend's PEM reader turns the
 * literal {@code \n} back into line breaks. Nothing is printed except the output paths.
 */
public final class GenSecrets {

    static final List<String> APPS = List.of("shop", "news", "limited");
    /** Must equal {@code RELIABLEPUSH_APPS_<ID>_IDENTITY_ISSUER} in backend.env.template. */
    static final String GRANT_ISSUER = "reliable-push-harness";
    private static final SecureRandom RANDOM = new SecureRandom();

    public static void main(String[] args) throws Exception {
        if (args.length < 1 || args.length > 2) {
            System.err.println("usage: java GenSecrets.java <outDir> [backend.env.template]");
            System.exit(2);
        }
        Path out = Path.of(args[0]);
        Path template = Path.of(args.length > 1 ? args[1] : "backend.env.template");
        Files.createDirectories(out);

        StringBuilder env = new StringBuilder();
        env.append("# Generated by harness/compose/GenSecrets.java for one E2E run. Never commit, never share.\n\n");
        env.append(Files.readString(template, StandardCharsets.UTF_8));
        env.append("\n# ---- per-run secrets ----\n");

        String dbPassword = random32();
        env.append("SPRING_DATASOURCE_PASSWORD=").append(dbPassword).append('\n');

        for (String app : APPS) {
            String id = app.toUpperCase(java.util.Locale.ROOT);
            String senderKey = random32();
            String grantSecret = random32();
            String hmacSecret = random32();
            env.append('\n').append("# app ").append(app).append('\n');
            env.append("RELIABLEPUSH_APPS_").append(id).append("_SENDERAPIKEYSHA256=").append(sha256Hex(senderKey))
                    .append('\n');
            env.append("RP_").append(id).append("_GRANT_SECRET=").append(grantSecret).append('\n');
            env.append("RP_").append(id).append("_HOOK_SECRET=").append(hmacSecret).append('\n');
            env.append("HARNESS_APPS_").append(id).append("_SENDERAPIKEY=").append(senderKey).append('\n');
            env.append("HARNESS_APPS_").append(id).append("_GRANTSECRET=").append(grantSecret).append('\n');
            env.append("HARNESS_APPS_").append(id).append("_HMACSECRET=").append(hmacSecret).append('\n');
            env.append("HARNESS_APPS_").append(id).append("_GRANTISSUER=").append(GRANT_ISSUER).append('\n');
        }

        KeyPairGenerator generator = KeyPairGenerator.getInstance("EC");
        generator.initialize(new ECGenParameterSpec("secp256r1"), RANDOM);
        KeyPair pair = generator.generateKeyPair();
        env.append("\n# device-token signing key (kid e2e)\n");
        env.append("RP_DEVICE_KEY_E2E='").append(pem("PRIVATE KEY", pair.getPrivate().getEncoded())).append("'\n");
        env.append("RP_DEVICE_PUB_E2E='").append(pem("PUBLIC KEY", pair.getPublic().getEncoded())).append("'\n");

        write(out.resolve("secrets.env"), env.toString());
        write(out.resolve("db.env"), "# Generated by GenSecrets.java; never commit.\nPOSTGRES_PASSWORD=" + dbPassword + "\n");
        System.out.println("wrote " + out.resolve("secrets.env") + " and " + out.resolve("db.env"));
    }

    /** 32 random bytes, base64url without padding (43 characters; safe unquoted in an env file). */
    static String random32() {
        byte[] bytes = new byte[32];
        RANDOM.nextBytes(bytes);
        return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
    }

    static String sha256Hex(String value) throws Exception {
        return HexFormat.of().formatHex(
                MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8)));
    }

    /** One PEM block on one line, lines separated by the two characters {@code \n}. */
    static String pem(String label, byte[] der) {
        String base64 = Base64.getEncoder().encodeToString(der);
        StringBuilder pem = new StringBuilder("-----BEGIN ").append(label).append("-----\\n");
        for (int i = 0; i < base64.length(); i += 64) {
            pem.append(base64, i, Math.min(base64.length(), i + 64)).append("\\n");
        }
        return pem.append("-----END ").append(label).append("-----\\n").toString();
    }

    /** Writes via a temp file in the same directory and moves it into place; mode 600 where POSIX permissions exist. */
    static void write(Path target, String content) throws IOException {
        Path tmp = Files.createTempFile(target.getParent(), ".gensecrets", ".tmp");
        try {
            try {
                Files.setPosixFilePermissions(tmp, PosixFilePermissions.fromString("rw-------"));
            } catch (UnsupportedOperationException e) {
                // non-POSIX file system: keep the default permissions
            }
            Files.writeString(tmp, content, StandardCharsets.UTF_8);
            Files.move(tmp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } finally {
            Files.deleteIfExists(tmp);
        }
    }
}
